#!/bin/bash

echo "======================================================="
echo "🚀 Начинаем развертывание e-qagaz на сервере (PVE2)..."
echo "======================================================="

# Останавливаем старые контейнеры, если они есть
echo "🛑 Остановка старых контейнеров (если есть)..."
docker-compose down

# Собираем и запускаем контейнеры в фоновом режиме
echo "📦 Сборка и запуск контейнеров Docker..."
docker-compose up -d --build

# Ждем пару секунд, чтобы база данных успела подняться
echo "⏳ Ожидание инициализации базы данных (10 секунд)..."
sleep 10

# Накатываем структуру базы данных Prisma (без интерактивных вопросов)
echo "🗄️ Создание таблиц в базе данных Postgres..."
docker-compose exec -T backend npx prisma db push --accept-data-loss

echo "======================================================="
echo "✅ Проект успешно развернут и запущен!"
echo "🌐 Теперь он доступен на 80 порту этого сервера."
echo "======================================================="
